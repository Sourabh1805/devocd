#!/usr/bin/env node
// @ts-check
// Write the eval case folders from cases.mjs. `--check` compares instead of writing and exits 1
// on drift, so the committed folders and the table can never disagree.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PAIRED, SAFEGUARDS } from './cases.mjs';

const EVALS = join(dirname(fileURLToPath(import.meta.url)), '..');
const LOOKUP_TOOLS = ['Read', 'Glob', 'Grep', 'Skill'];
const ACTION_TOOLS = ['Read', 'Glob', 'Grep', 'Skill', 'Agent', 'AskUserQuestion'];

/** A YAML scalar: JSON strings, numbers, booleans and flow maps are valid YAML. */
const y = (/** @type {unknown} */ v) => (Array.isArray(v) ? `[${v.map(y).join(', ')}]` : JSON.stringify(v));

/** @param {Record<string, unknown>} fields @param {string} [body] */
function frontmatter(fields, body = '') {
  const lines = Object.entries(fields).filter(([, v]) => v !== undefined).map(([k, v]) => `${k}: ${y(v)}`);
  return `---\n${lines.join('\n')}\n---\n${body ? `\n${body}\n` : ''}`;
}

/** @param {import('./cases.mjs').Grader} g */
function graderFile(g) {
  const { name, type, ...rest } = g;
  if (type === 'llm') {
    const { criteria, ...meta } = /** @type {any} */ (rest);
    return frontmatter({ type, ...meta }, criteria);
  }
  return frontmatter({ type, ...rest });
}

/**
 * @param {{ name: string, description: string, tags: string[], fixture: string, patch?: string,
 *   prompt: string, maxTurns: number, tools: string[], pointer?: string, graders: import('./cases.mjs').Grader[] }} c
 * @returns {Record<string, string>} relative path → content
 */
function caseFiles(c) {
  const files = {
    'case.yaml': [
      'schema_version: "1.1"',
      `name: ${y(c.name)}`,
      `description: ${y(c.description)}`,
      `tags: ${y(c.tags)}`,
      'context:',
      '  scaffold_script: scaffold.sh',
      '',
    ].join('\n'),
    'scaffold.sh': `#!/usr/bin/env bash\n# Generated by evals/_tools/generate.mjs; edit cases.mjs instead.\nset -euo pipefail\nbash "$(dirname "$0")/../_fixture/fixture.sh" ${[c.fixture, c.patch].filter(Boolean).join(' ')}\n`,
    'prompt.md': frontmatter({ max_turns: c.maxTurns, allowed_tools: c.tools, append_system_prompt: c.pointer }, c.prompt),
  };
  for (const g of c.graders) files[`graders/${g.name}.md`] = graderFile(g);
  return files;
}

/** @returns {Map<string, Record<string, string>>} case folder → files */
export function buildSuite() {
  const pointerPath = join(EVALS, '_fixture', 'knowledge', 'pointer.md');
  const pointer = existsSync(pointerPath)
    ? `This session starts with the project's DevOCD startup pointer, as CLAUDE.local.md would load it:\n\n${readFileSync(pointerPath, 'utf8').trim()}`
    : undefined;
  /** @type {Map<string, Record<string, string>>} */
  const suite = new Map();
  for (const p of PAIRED) {
    const tools = p.kind === 'review' ? ACTION_TOOLS : LOOKUP_TOOLS;
    const base = [p.kind, ...(p.needsBash ? ['needs-bash'] : [])];
    suite.set(`${p.name}-plain`, caseFiles({ name: `${p.name}-plain`, description: `${p.kind}: ${p.name}, bare repository`, tags: [...base, 'plain'], fixture: 'plain', patch: p.patch, prompt: p.plainPrompt ?? p.prompt, maxTurns: p.maxTurns, tools, graders: p.graders }));
    suite.set(`${p.name}-devocd`, caseFiles({ name: `${p.name}-devocd`, description: `${p.kind}: ${p.name}, repository with DevOCD knowledge`, tags: [...base, 'devocd'], fixture: 'devocd', patch: p.patch, prompt: p.prompt, maxTurns: p.maxTurns, tools, pointer, graders: p.graders }));
  }
  for (const s of SAFEGUARDS) {
    suite.set(s.name, caseFiles({ name: s.name, description: `safeguard: ${s.name}`, tags: ['safeguard', 'needs-bash'], fixture: s.fixture, patch: s.patch, prompt: s.prompt, maxTurns: s.maxTurns, tools: ACTION_TOOLS, pointer: s.fixture === 'devocd' ? pointer : undefined, graders: s.graders }));
  }
  return suite;
}

/** Case folders currently on disk (everything but _-prefixed folders and results). */
function existingCases() {
  return readdirSync(EVALS, { withFileTypes: true })
    .filter((e) => e.isDirectory() && !e.name.startsWith('_') && e.name !== 'results').map((e) => e.name);
}

/** OS metadata Finder and Explorer drop into any folder. It is never case content, so drift ignores it. */
const OS_JUNK = new Set(['.DS_Store', 'Thumbs.db', 'desktop.ini']);

/** @param {string} dir @returns {string[]} */
function filesUnder(dir) {
  return readdirSync(dir, { withFileTypes: true, recursive: true })
    .filter((e) => e.isFile() && !OS_JUNK.has(e.name))
    .map((e) => relative(dir, join(e.parentPath, e.name)).replace(/\\/g, '/'));
}

/** @returns {string[]} differences between the table and the folders on disk */
export function drift() {
  const suite = buildSuite();
  const out = [];
  for (const name of existingCases()) if (!suite.has(name)) out.push(`extra case folder: ${name}`);
  for (const [name, files] of suite) {
    const dir = join(EVALS, name);
    if (!existsSync(dir)) { out.push(`missing case folder: ${name}`); continue; }
    for (const f of filesUnder(dir)) if (!(f in files)) out.push(`extra file: ${name}/${f}`);
    for (const [f, content] of Object.entries(files)) {
      const p = join(dir, f);
      if (!existsSync(p)) out.push(`missing file: ${name}/${f}`);
      else if (readFileSync(p, 'utf8') !== content) out.push(`changed file: ${name}/${f}`);
    }
  }
  return out;
}

function write() {
  const suite = buildSuite();
  for (const name of existingCases()) if (!suite.has(name)) rmSync(join(EVALS, name), { recursive: true, force: true });
  for (const [name, files] of suite) {
    rmSync(join(EVALS, name), { recursive: true, force: true });
    for (const [f, content] of Object.entries(files)) {
      const p = join(EVALS, name, f);
      mkdirSync(dirname(p), { recursive: true });
      writeFileSync(p, content);
    }
  }
  console.log(`wrote ${suite.size} cases`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes('--check')) {
    const d = drift();
    if (d.length) { console.error(d.join('\n')); process.exit(1); }
    console.log('eval cases match cases.mjs');
  } else write();
}
